#!/usr/bin/env node
/**
 * Optimises the photography already in public/img for the web:
 *   - re-encodes every WebP at a web-friendly quality
 *   - emits 480w and 900w responsive variants alongside each master image
 *
 * The variants let the browser fetch a phone-sized file on a phone instead of
 * the full-resolution one.
 *
 * Run: node scripts/optimise-images.mjs
 */
import { execFile } from 'node:child_process'
import { readdir, readFile, stat, rename, writeFile } from 'node:fs/promises'
import { promisify } from 'node:util'
import { dirname, resolve, basename, extname } from 'node:path'
import { fileURLToPath } from 'node:url'

const exec = promisify(execFile)
const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(HERE, '..')
const IMG_DIR = resolve(ROOT, 'public/img')

const QUALITY = '76'
const WIDTHS = [480, 900]

async function sh(cmd, args) {
  const { stdout } = await exec(cmd, args, { maxBuffer: 1024 * 1024 * 64 })
  return stdout.trim()
}

async function sizeOf(path) {
  const out = await sh('sh', ['-c', `stat -f%z "${path}"`])
  return Number(out)
}

async function widthOf(path) {
  const out = await sh('sips', ['-g', 'pixelWidth', path])
  const m = out.match(/pixelWidth:\s*(\d+)/)
  return m ? Number(m[1]) : 0
}

async function run() {
  const files = (await readdir(IMG_DIR)).filter(
    (f) => extname(f).toLowerCase() === '.webp' && !/-480\.webp$/.test(f) && !/-900\.webp$/.test(f)
  )

  let before = 0
  let after = 0
  const manifest = {}

  // Skip masters that were already re-encoded (keeps the script idempotent so
  // repeated runs do not stack lossy artefacts).
  const statePath = resolve(HERE, '.img-state.json')
  let state = {}
  try {
    state = JSON.parse(await readFile(statePath, 'utf8'))
  } catch {
    state = {}
  }

  for (const file of files) {
    const master = resolve(IMG_DIR, file)
    const stem = basename(file, '.webp')
    const originalSize = await sizeOf(master)
    const { mtimeMs } = await stat(master)
    before += originalSize

    // Re-encode the master at the target quality.
    if (state[file] !== mtimeMs) {
      const tmpMaster = resolve(IMG_DIR, `.tmp-${file}`)
      await sh('cwebp', [
        '-quiet',
        '-q',
        QUALITY,
        '-m',
        '6',
        '-sharp_yuv',
        master,
        '-o',
        tmpMaster,
      ])
      await rename(tmpMaster, master)
      state[file] = (await stat(master)).mtimeMs
    }

    // Responsive variants.
    const masterWidth = await widthOf(master)
    const widths = []
    for (const width of WIDTHS) {
      if (masterWidth && masterWidth <= width) continue
      const out = resolve(IMG_DIR, `${stem}-${width}.webp`)
      await sh('cwebp', [
        '-quiet',
        '-q',
        QUALITY,
        '-m',
        '6',
        '-sharp_yuv',
        '-resize',
        String(width),
        '0',
        master,
        '-o',
        out,
      ])
      widths.push(width)
    }

    manifest[stem] = { master: masterWidth, widths }
    after += await sizeOf(master)
    console.log(`✓ ${file}`)
  }

  await writeFile(
    resolve(ROOT, 'src/data/images.ts'),
    `// Auto-generated by scripts/optimise-images.mjs — responsive image variants.\n` +
      `export interface ImageVariant {\n` +
      `  master: number\n` +
      `  widths: number[]\n` +
      `}\n\n` +
      `export const IMAGE_VARIANTS: Record<string, ImageVariant> = ${JSON.stringify(manifest, null, 2)}\n`
  )
  await writeFile(statePath, JSON.stringify(state, null, 2))

  console.log(
    `\nMasters: ${(before / 1024 / 1024).toFixed(2)} MB → ${(after / 1024 / 1024).toFixed(2)} MB ` +
      `(+ ${WIDTHS.join('w, ')}w variants)`
  )
}

run().catch((err) => {
  console.error(err)
  process.exit(1)
})
